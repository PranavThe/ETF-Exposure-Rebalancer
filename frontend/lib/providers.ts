const BY_ID = new Map<string, Provider>();
const PREFIXES: [string, Provider][] = [];
for (const [id, name, prefixes] of ROWS) {
  const provider: Provider = { id, name, logo: LOGOS.has(id) ? `/logos/${id}.png` : null };
  BY_ID.set(id, provider);
  for (const p of prefixes.split("|")) PREFIXES.push([clean(p), provider]);
}
PREFIXES.sort((a, b) => b[0].length - a[0].length);

/** Every known provider, in rough order of catalog size. */
export const PROVIDERS: Provider[] = [...BY_ID.values()];

function clean(s: string): string {
  return s.replace(/[‘’]/g, "'").replace(/\s+/g, " ").trim().toLowerCase();
}

function match(text: string): Provider | null {
  const t = clean(text);
  for (const [prefix, provider] of PREFIXES) {
    if (t.startsWith(prefix) && !/[a-z0-9]/.test(t.charAt(prefix.length))) return provider;
  }
  for (const [re, id] of ANYWHERE) if (re.test(text.trim())) return BY_ID.get(id) ?? null;
  return null;
}

/** The ETF's issuer, or null when the name doesn't say. */
export function providerOf(etf: { ticker: string; name?: string | null; issuer?: string | null }): Provider | null {
  const byTicker = TICKERS[etf.ticker?.trim().toUpperCase()];
  if (byTicker) return BY_ID.get(byTicker) ?? null;
  return (etf.name && match(etf.name)) || (etf.issuer && match(etf.issuer)) || null;
}
